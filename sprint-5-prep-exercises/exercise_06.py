# Think of the advantages of using methods instead of free functions. Write them down in your notebook.

# Better readability of code
# - Method names can be simplified as they only apply to that class, they are contained within the class which is more
#   organised and method names can be reused in different classes.

# Encapsulation of that function only to class - cleaner and better security.
# - This can allow for discoverability of methods when writing code using . in an IDE.
# - Data can be protected from outside functions changing it, this allows for control over what can be changed using
#   only the inbuilt methods of a class

# Potential drawback: For a function that may want to be used on class objects from multiple different classes it may
# be better to use a function instead of repeated a method for each class.
